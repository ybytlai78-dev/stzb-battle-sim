/**
 * 主站更新公告（公告栏的数据源，**版本号的唯一真源**）。
 *
 * 维护规则速记（完整流程见 `docs/公告栏维护.md`）：
 *  1. `ANNOUNCEMENTS` 按版本**倒序** —— 数组第一项就是当前上线版本，
 *     `SITE_VERSION` 由它派生：底栏版本标记 / 公告栏标题 / 未读红点全部跟着它走，
 *     所以**不存在「改了版本号但忘了写公告」的可能**；
 *  2. **每次部署上线都在最前面插入一条新记录**（版本号 = 上一条 +0.1，日期 = 上线当天），
 *     `web/changelog.test.ts` 会把格式 / 倒序 / 去重 / 非空 / 与 `SITE_VERSION` 一致全部守住；
 *  3. 文案面向玩家：说清「多了什么、能干什么」，不写内部字段名与实现细节；
 *  4. 数据随代码提交、编译进带 hash 的产物 —— 运行时不需要请求，离线可用，Service Worker 不用改。
 */

/** 一组同性质的更新条目 */
export type ChangeKind = '新增' | '优化' | '修复' | '调整' | '说明';

export interface ChangeGroup {
  kind: ChangeKind;
  /** 该组下的条目（至少 1 条，玩家视角的一句话改动） */
  items: string[];
}

export interface Announcement {
  /** 主站版本号：`主版本.次版本`（也允许 `1.0.1` 这种三段） */
  version: string;
  /** 上线日期 YYYY-MM-DD */
  date: string;
  /** 一句话主题（版本块标题） */
  title: string;
  /** 开篇导读（可选） */
  summary?: string;
  /** 更新条目，按「新增 / 优化 / 修复 / 调整 / 说明」分组 */
  groups: ChangeGroup[];
}

