/** localStorage：玩家**已读**到的版本号（红点依据；打开公告栏时写入，各设备各记一份） */
export const ANNOUNCEMENT_SEEN_KEY = 'stzb_site_version_seen';

/**
 * localStorage：已经**弹窗提醒**过的版本号（防重复弹窗的水位；与"已读"分开记）。
 *
 * 为什么要两个 key：首次运行（新装 / 清了存储）要"不弹窗但仍留红点"——
 *  - 首次运行：把**弹窗水位**推到当前版本（不打扰），**已读水位不写**（红点亮着，点开即清）；
 *  - 之后每个新版本：弹窗水位落后 → 弹一次；打开即写已读水位，红点随之灭。
 * 合成一个 key 的话，这两个状态必有一个表达不出来（要么首启就弹窗 = 触发发布，要么红点永远不亮）。
 */
export const ANNOUNCEMENT_NOTIFIED_KEY = 'stzb_site_version_notified';

/** 版本号 → 数字段：`1.2.3` → `[1, 2, 3]` */
export function versionParts(version: string): number[] {
  return version.split('.').map((n) => Number(n));
}

/** 版本比较：a > b 返回正数、相等返回 0（缺位按 0 补，`1.1` 与 `1.1.0` 等价） */
export function compareVersions(a: string, b: string): number {
  const pa = versionParts(a);
  const pb = versionParts(b);
  const len = Math.max(pa.length, pb.length);
  for (let i = 0; i < len; i += 1) {
    const diff = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (diff !== 0) return diff;
  }
  return 0;
}

/** 最新一条公告（= 数组第一项） */
export function latestAnnouncement(): Announcement {
  return ANNOUNCEMENTS[0];
}

/** 按版本号取公告（找不到返回 undefined） */
export function announcementByVersion(version: string): Announcement | undefined {
  return ANNOUNCEMENTS.find((a) => a.version === version);
}

/** 一条公告的改动条目总数（面板里「共 N 条」用） */
export function changeCount(ann: Announcement): number {
  return ann.groups.reduce((n, g) => n + g.items.length, 0);
}
