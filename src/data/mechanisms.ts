/** 取战法用到的机制码（升序）；未收录返回空数组 */
export function mechanismCodesOf(skillId: string): number[] {
  const m = SKILL_MECHANISMS[skillId];
  return m ? Object.keys(m).map(Number).sort((a, b) => a - b) : [];
}

/** 取战法用到的机制名（供 UI 展示） */
export function mechanismNamesOf(skillId: string): string[] {
  return mechanismCodesOf(skillId).map((c) => {
    const e = BY_CODE.get(c);
    return e ? (e.scene ? `${e.name}(${e.scene})` : e.name) : `#${c}`;
  });
}

/** 战法的总槽位数（未收录返回 0） */
export function slotCountOf(skillId: string): number {
  const m = SKILL_MECHANISMS[skillId];
  return m ? Object.values(m).reduce((a, b) => a + b, 0) : 0;
}
